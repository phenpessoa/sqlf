#!/bin/sh
# Generates builtins_gen.go from the pg_catalog of a Postgres container.
# The major version must match the parser used by go-pgquery (Postgres 17).
set -eu

image=postgres:17
name=sqlf-builtins-gen-$$

docker run -d --rm --name "$name" -e POSTGRES_PASSWORD=x "$image" >/dev/null
trap 'docker stop "$name" >/dev/null 2>&1 || true' EXIT

i=0
until docker exec "$name" pg_isready -U postgres >/dev/null 2>&1; do
	i=$((i + 1))
	if [ "$i" -gt 60 ]; then
		echo "postgres did not start" >&2
		exit 1
	fi
	sleep 1
done
# pg_isready can succeed before the init script restarts the server.
sleep 2

q() {
	docker exec "$name" psql -U postgres -Atc "$1"
}

version=$(q "show server_version")
funcs=$(q "select distinct proname from pg_proc where pronamespace = 'pg_catalog'::regnamespace order by 1")
types=$(q "select distinct typname from pg_type where typnamespace = 'pg_catalog'::regnamespace and typtype in ('b', 'p', 'r', 'm') and typname !~ '^_' order by 1")

{
	echo "// Code generated by gen.sh from PostgreSQL $version; DO NOT EDIT."
	echo
	echo "package builtins"
	echo
	echo "var functions = map[string]struct{}{"
	echo "$funcs" | while read -r f; do printf '\t"%s": {},\n' "$f"; done
	echo "}"
	echo
	echo "var types = map[string]struct{}{"
	echo "$types" | while read -r t; do printf '\t"%s": {},\n' "$t"; done
	echo "}"
} >builtins_gen.go

gofmt -w builtins_gen.go
